// 계절 농담 — 흐름 탭 한 줄에 섞여 나간다.
//
// app/jokes.ts 와 파일을 나눈 이유: **축이 다르다.**
// 기존 농담은 mood(숫자)가 고르지만, 이건 mood 위에 **날짜**가 한 겹 더 얹힌다.
// 한 파일에 섞으면 겨울 문구가 8월에 나오는 사고를 막을 방법이 없다.
//
// ── 반구 (이 파일에서 제일 중요한 제약) ────────────────────────────
// 남반구(호주·뉴질랜드·브라질·아르헨티나)는 계절이 반대다.
// wavu 지역 코드는 `asia | am | eu | me | oce` 인데 **`am` 안에 북미와 남미가
// 같이 들어 있어 반구를 가를 수 없다.** 지역으로 추정하지 않는다 —
// 시간대에서 배운 것과 같다("지역을 못 읽으면 추정하지 않는다").
//
// 대신 **언어로 가른다.** ko·ja 는 북반구가 확정이므로 여기에만 넣는다.
// en 은 빈 배열로 둔다 — 비어 있으면 호출부가 알아서 기본 농담으로 떨어진다.
// 나중에 남반구 문구를 따로 쓸 생각이라면 그때 en 을 열되, 반구 판정 근거가
// 먼저 있어야 한다. **없는 근거로 계절을 말하지 말 것.**
//
// 톤 규칙은 app/jokes.ts 와 같다 — 놀리되 비하하지 않고, 실제 고통(질병·생활고)은
// 소재로 삼지 않는다. 계절 소재에서 특히 조심할 것:
//   - 난방비·전기요금은 자조 개그 범위. '돈이 없어 못 켠다'로는 쓰지 않는다.
//   - 명절은 '잔소리' 정도까지. 가족 갈등은 쓰지 않는다.
//   - 더위·추위로 인한 실제 건강 피해(온열질환·저체온)는 쓰지 않는다.

import type { Lang } from './i18n';

export type Season = 'spring' | 'summer' | 'autumn' | 'winter';

/**
 * 계절 문구는 mood 4단계를 그대로 따라가지 않는다.
 * 4계절 × 4수위 × 언어면 pool 이 48개가 되는데, 계절 소재는 그만큼 갈리지 않는다.
 * 올라갈 때(hot·steady)와 내려갈 때(cooling·cold) 둘이면 충분하다.
 * `down` 은 cooling·cold 공용이므로 **수위를 cooling 에 맞춰 순하게 쓴다** —
 * 낮은 쪽에 맞추면 cold 에서 순해질 뿐이지만, 반대로 맞추면 cooling 에서 과해진다.
 */
export type SeasonTone = 'up' | 'down';

/**
 * KST 벽시계 기준 계절 (기상청 구분: 3~5 봄 / 6~8 여름 / 9~11 가을 / 12~2 겨울).
 *
 * `dt` 는 lib/tekken/models.ts 규약대로 **KST 벽시계를 UTC 필드에 담고 있다.**
 * 반드시 `getUTCMonth()` 로 읽을 것 — `getMonth()` 를 쓰면 보는 사람 브라우저
 * 시간대가 끼어들어 연말·연초에 계절이 하루씩 어긋난다.
 */
export function seasonOf(dt: Date): Season {
  const m = dt.getUTCMonth() + 1;
  if (m === 12 || m <= 2) return 'winter';
  if (m <= 5) return 'spring';
  if (m <= 8) return 'summer';
  return 'autumn';
}

