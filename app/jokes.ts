/** 안정적인 씨앗으로 배열에서 하나 고르기. */
function pick<T>(pool: T[], seed: number): T {
  const i = ((Math.trunc(seed) % pool.length) + pool.length) % pool.length;
  return pool[i];
}

/**
 * 흐름 탭 문구.
 * `seed` 는 조회 결과에서 나온 안정적인 정수를 넘긴다 —
 * 같은 조회에서는 항상 같은 문구가 나오고, 조회가 달라지면 문구도 달라진다.
 */
export function pickJoke(
  mood: Mood,
  lang: Lang,
  seed: number,
  pp: number,
  streak: number,
  season?: Season | null,
  facts?: QuipFacts | null,
): string {
  // ── 우선순위 사다리 ──────────────────────────────────────────────
  // 좁은 조건이 이긴다. 예전에는 축마다 `seed % N` 으로 섞었는데, 그러면 축을 늘릴수록
  // **드문 사건이 묻힌다** — 10,000판 달성은 평생 한 번인데 25% 확률로 계절 문구에
  // 밀리면 안 된다. 사건은 순서대로 먼저 보고, 특성은 기본 풀과 섞는다.
  //
  //   마일스톤 > 최고 갱신 > 승단·강등 > 복귀 > 연승 > 오늘 몰림 > 시각 > 계절 > 기본
  const { events, traits } = factPools(facts ?? null, lang, mood);
  if (events.length > 0) return pick(events[0], seed); // 빈 pool 은 factPools 가 이미 걸렀다

  // 계절 문구는 mood 가 아니라 **날짜**가 여는 축이라 pool 을 따로 본다.
  // 계절을 모르면(=null) 이 갈래는 통째로 건너뛴다 — 없는 근거로 계절을 말하지 않는다.
  if (season) {
    const sp = seasonPool(season, mood === 'hot' || mood === 'steady' ? 'up' : 'down', lang);
    // 언어에 계절 문구가 없으면(en) 비어 있다 → 자동으로 기본 농담으로 떨어진다.
    if (sp.length > 0 && seed % SEASON_EVERY === 0) return pick(sp, seed);
  }

  // 특성 문구는 늘 참이라 우선하면 기본 풀을 영영 밀어낸다. 확률로만 끼워 넣는다.
  if (traits.length > 0 && seed % TRAIT_EVERY === 0) return pick(traits, seed);

  // 연패가 없으면 연패를 소재로 한 문구는 후보에서 뺀다.
  const pool = JOKES[mood][lang].filter(
    (j) => typeof j === 'function' || streak >= STREAK_MIN,
  );
  if (pool.length === 0) return '';
  const j = pick(pool, seed);
  return (typeof j === 'function' ? j : j.fn)(pp, streak);
}

/** 연습 권유 한 줄 (농담 다음 줄). 씨앗을 농담과 어긋나게 줘야 짝이 다양해진다. */
export function pickCoach(mood: Mood, lang: Lang, seed: number): string {
  const pool = COACH[mood][lang];
  return pool.length ? pick(pool, seed) : '';
}

/** 요약 카드 아래 컨디션 한 줄. */
export function pickCondition(
  condition: Condition,
  lang: Lang,
  seed: number,
  facts: ConditionFacts,
): string {
  const pool = CONDITIONS[condition][lang];
  if (pool.length === 0) return '';
  return pick(pool, seed)(facts);
}
